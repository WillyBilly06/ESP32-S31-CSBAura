def crc16_arc(data):
    crc = 0
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc


def model_by_pid(pid):
    for m in MODELS:
        if m[0] == pid:
            return m
    return None


def model_from_arg(text):
    """--model: a PID (2040, 0x2040) or a name ("charge 5")"""
    t = (text or "").strip().lower()
    try:
        m = model_by_pid(int(t, 16))
        if m:
            return m
    except ValueError:
        pass
    hits = [m for m in MODELS if t in m[1].lower()]
    exact = [m for m in hits if m[1].lower().endswith(t)]
    if len(exact) == 1 or len(hits) == 1:
        return (exact or hits)[0]
    raise SystemExit(f"unknown model {text!r} - one of: " + ", ".join(f"{m[1]} ({m[0]:04X})" for m in MODELS))


def make_cfg(color_id, name, ident=None, model=DEFAULT_PID):
    """the s31cfg partition image, version 3 (see s31-btstack-speaker/main/s31_ident.c);
    ident = this speaker's Bluetooth address (6 bytes), None/zeros = the chip's own MAC;
    model = the JBL product ID the board is"""
    nb = (name or "").encode("utf-8")[:NAME_MAX]
    body = b"S31C" + bytes([3, color_id & 0xFF, 0, len(nb)]) + nb.ljust(NAME_MAX, b"\0")
    body += bytes(ident or bytes(6))
    body += struct.pack("<H", model & 0xFFFF)
    body += struct.pack("<H", crc16_arc(body))
    return body.ljust(CFG_SIZE, b"\xff")


def new_identity():
    """a fresh Bluetooth address for "New speaker on every flash": Espressif's 30:ED:A0 and 3
    random bytes, outside the reserved inquiry LAPs 9E8B00..9E8B3F"""
    while True:
        tail = os.urandom(3)
        if not (tail[0] == 0x9E and tail[1] == 0x8B and tail[2] <= 0x3F):
            return bytes([0x30, 0xED, 0xA0]) + tail


def cfg_identity(blob):
    """the Bluetooth address in an s31cfg image (v2 / v3), None when it has none"""
    if len(blob) < 50 or blob[:4] != b"S31C" or blob[4] not in (2, 3):
        return None
    body = 46 if blob[4] == 2 else 48
    if struct.unpack_from("<H", blob, body)[0] != crc16_arc(blob[:body]):
        return None
    ident = bytes(blob[40:46])
    return None if ident in (bytes(6), bytes([0xFF]) * 6) or ident[0] & 1 else ident


def addr_str(ident):
    return ":".join(f"{b:02X}" for b in ident)


def load_build(build_dir):
    path = os.path.join(build_dir, "flasher_args.json")
    if not os.path.isfile(path):
        raise FileNotFoundError(f"no build in {build_dir} - build first")
    with open(path, encoding="utf-8") as f:
        args = json.load(f)
    files = []
    for off, rel in args["flash_files"].items():
        p = os.path.join(build_dir, rel)
        if not os.path.isfile(p):
            raise FileNotFoundError(f"{rel} is missing from {build_dir}")
        files.append((off, p))
    return args, files


def run_esptool(argv, log):
    import esptool
    log("esptool " + " ".join(argv) + "\n")
    old_out, old_err = sys.stdout, sys.stderr

    class W(io.TextIOBase):
        def write(self, s):
            log(s)
            return len(s)

    sys.stdout = sys.stderr = W()
    try:
        esptool.main(argv)
    finally:
        sys.stdout, sys.stderr = old_out, old_err


# Fastest first: esptool's flasher stub for the S31 at 3 Mbaud (compressed writes, about 2 Mbit/s).
# ESP-IDF still marks the S31 a bring-up chip and asks for no stub: the ROM loader managed about
# 350 kbit/s, about 80 s per flash. An adapter that cannot do 3 Mbaud falls back step by step.
SPEEDS = [(True, 3000000), (True, 921600), (False, 921600)]


def close_open_ports():
    import gc
    try:
        import serial
    except ImportError:
        return
    for o in gc.get_objects():
        try:
            if isinstance(o, serial.SerialBase) and o.is_open:
                o.close()
        except Exception:
            pass


def run_esptool_fast(tail, port, chip, before, after, log):
    last = None
    for stub, baud in SPEEDS:
        argv = ["--chip", chip, "--port", port, "--baud", str(baud), "--before", before, "--after", after]
        if not stub:
            argv.append("--no-stub")
        try:
            run_esptool(argv + tail, log)
            return
        except SystemExit as e:
            if e.code in (None, 0):
                return
            last = e
        except Exception as e:                      # esptool's FatalError, serial timeouts
            last = e
        close_open_ports()                          # esptool can leave the port open on an error
        log(f"\n{'stub' if stub else 'ROM loader'} at {baud} baud failed ({last}) - trying slower\n")
    raise RuntimeError(f"esptool failed: {last}")


def board_identity(port, tmp, log):
    """the identity the board's s31cfg holds now (None: the chip's own MAC). A board that cannot be
    read stops the flash: writing the chip's own address over an identity an earlier flash gave it
    would silently cost the speaker every pairing it has."""
    path = os.path.join(tmp, "s31cfg_board.bin")
    try:
        os.remove(path)                             # never read back an older board's file
    except OSError:
        pass
    try:
        run_esptool_fast(["read-flash", hex(CFG_OFFSET), "64", path], port, "esp32s31", "default-reset", "no-reset", log)
        with open(path, "rb") as f:
            return cfg_identity(f.read())
    except Exception as e:
        raise RuntimeError(f"could not read the board's identity ({' '.join(str(e).split())}). Nothing was written: flashing now "
                           "could change its Bluetooth address and lose its pairings. Check the cable / port "
                           "and try again (or choose Erase / New speaker).") from e


def flash(project, port, color_id, name, erase, color_only, log, model=DEFAULT_PID, new_id=False):
    """new_id: this flash makes a new speaker (a fresh Bluetooth address; phones pair it as a new
    one). Otherwise the board keeps the identity it has (read back from it); erase goes back to
    the chip's own address."""
    build_dir = project_file(project, PROJECT_SUBDIR, "build")
    # a fixed work file, overwritten each time and never deleted: esptool can still hold it
    # open when we return, and Windows refuses to delete an open file (WinError 32)
    tmp = os.path.join(tempfile.gettempdir(), "S31Flasher")
    os.makedirs(tmp, exist_ok=True)
    if True:
        if new_id:
            ident = new_identity()
            log(f"New speaker: Bluetooth address {addr_str(ident)} (phones pair it as a new one)\n")
        elif not erase:
            # off: the board stays the speaker it is now (its address and pairings), whether
            # that is the chip's own address or one an earlier flash gave it
            ident = board_identity(port, tmp, log)
            log(f"Identity kept: {addr_str(ident) if ident else 'the chip MAC'} (pairings kept)\n")
        else:
            ident = None
            log("Identity: the chip's own Bluetooth address (the board is erased)\n")
        cfg = os.path.join(tmp, "s31cfg.bin")
        with open(cfg, "wb") as f:
            f.write(make_cfg(color_id, name, ident=ident, model=model))
        if color_only:
            run_esptool_fast(["write-flash", hex(CFG_OFFSET), cfg], port, "esp32s31", "default-reset", "hard-reset", log)
            log(f"\nModel {model:04X}, color 0x{color_id:02X} set. The board restarts with it.\n")
            return
        args, files = load_build(build_dir)
        tones = find_tones(project, build_dir)
        if tones:
            files.append((hex(TONES_OFFSET), tones))
        log(f"Prompt tones: {tones or 'none found (the board keeps the ones it has)'}\n")
        extra = args.get("extra_esptool_args", {})
        chip = extra.get("chip", "esp32s31")
        before = extra.get("before", "default-reset").replace("_", "-")
        after = extra.get("after", "hard-reset").replace("_", "-")
        if erase:   # erase-region: the S31 ROM has no erase-flash
            run_esptool_fast(["erase-region", "0x0", hex(FLASH_SIZE)], port, chip, before, "no-reset", log)
        wf = [a.replace("_", "-") for a in args.get("write_flash_args", [])]
        pairs = []
        for off, p in files + [(hex(CFG_OFFSET), cfg)]:
            pairs += [off, p]
        # --skip-flashed: an image already on the board (same MD5) is not written again. The 2 MB
        # tones image rarely changes, and the bootloader and partition table almost never do
        run_esptool_fast(["write-flash", "--skip-flashed"] + wf + pairs, port, chip, before, after, log)
        m = model_by_pid(model)
        log(f"\nDone: {m[1] if m else hex(model)}, color 0x{color_id:02X}{', name ' + repr(name) if name else ''}. "
            "The board restarts as that speaker.\n")


def ports():
    try:
        from serial.tools import list_ports
        return [p.device for p in list_ports.comports()]
    except Exception:
        return []


def color_from_args(a, model):
    if a.color_id is not None:
        return int(a.color_id, 0)
    for nm, cid, _ in model[2]:
        if nm.lower().startswith(a.color.lower()):
            return cid
    raise SystemExit(f"unknown color {a.color!r} for {model[1]} - one of: " + ", ".join(c[0] for c in model[2]))


